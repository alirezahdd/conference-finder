// Weekly job (.github/workflows/update-deadlines.yml): downloads ccf-deadlines and writes data-ccf.js,
// the snapshot the page merges into data.js on load (same rules as the "Check for updates" button).
// Run locally with: npm install --no-save js-yaml@4.1.0 && node scripts/update-ccf.mjs
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const yaml = require("js-yaml");
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const U = require(path.join(ROOT, "updater.js"));
const OUT = path.join(ROOT, "data-ccf.js");

// Evaluate a browser script that assigns to window.* and return that window.
const load = (file) => {
  const ctx = { window: {} };
  vm.createContext(ctx);
  if (fs.existsSync(file)) vm.runInContext(fs.readFileSync(file, "utf8"), ctx);
  return ctx.window;
};

const conferences = load(path.join(ROOT, "data.js")).CONFERENCES;
const previous = load(OUT).CCF_SNAPSHOT;

const res = await fetch(U.SOURCE);
if (!res.ok) throw new Error(`ccf-deadlines answered ${res.status}`);
const data = U.subset(yaml.load(await res.text()), [...new Set(conferences.map((c) => c.name))]);

const { changes, kept, added, missing } = U.merge(conferences, data);
const summary = [
  `## ccf-deadlines check`,
  `${changes.length} date(s) updated, ${added.length} new cycle(s), ${kept.length} difference(s) kept (data.js is confirmed).`,
  ...added.map((a) => `- **${a.label}**: new cycle, paper deadline ${a.deadline}`),
  ...changes.map((c) => `- **${c.label}** ${c.field}: ${c.from} → ${c.to}`),
  ...kept.map((k) => `- kept **${k.label}** ${k.field}: data.js ${k.ours}, ccf-deadlines ${k.theirs}`),
  missing.length ? `\nNot in ccf-deadlines: ${missing.join(", ")}` : "",
].join("\n");
console.log(summary);
if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, summary + "\n");

// Rewrite the snapshot only when the data changed, so the weekly run does not commit noise.
if (previous && JSON.stringify(previous.data) === JSON.stringify(data)) {
  console.log("\nccf-deadlines unchanged; data-ccf.js left as is.");
} else {
  const snapshot = { fetchedAt: new Date().toISOString(), data };
  fs.writeFileSync(OUT, [
    "/* Generated by scripts/update-ccf.mjs (weekly GitHub Action). Do not edit by hand. */",
    "/* ccf-deadlines records for the conferences in data.js; app.js merges them on load (see updater.js). */",
    `window.CCF_SNAPSHOT = ${JSON.stringify(snapshot)};`,
    "",
  ].join("\n"));
  console.log("\nWrote data-ccf.js.");
}
